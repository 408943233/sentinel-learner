def generate_prototype_from_task(task_path: str, output_dir: str) -> str:
    """
    从任务目录生成原型Demo
    
    Args:
        task_path: 任务目录路径
        output_dir: 输出目录
        
    Returns:
        生成的HTML文件路径
    """
    task_dir = Path(task_path)
    
    # 查找页面结构文件
    structure_file = task_dir / 'output' / 'page_structure.json'
    
    if not structure_file.exists():
        # 尝试从DOM snapshot提取
        dom_files = list(task_dir.glob('dom/snapshot_*.json'))
        if dom_files:
            from ..extractors.page_structure_extractor import PageStructureExtractor
            extractor = PageStructureExtractor(str(dom_files[0]))
            extractor.save(task_dir / 'output')
            structure_file = task_dir / 'output' / 'page_structure.json'
    
    if not structure_file.exists():
        print(f"[PrototypeGenerator] 未找到页面结构数据: {task_path}")
        return ""
    
    # 生成原型
    generator = PrototypeGenerator(str(structure_file))
    return generator.generate(output_dir)
