    def __init__(self, page_structure_path: str):
        """
        初始化生成器
        
        Args:
            page_structure_path: 页面结构JSON文件路径
        """
        self.structure_path = Path(page_structure_path)
        self.page_structure = self._load_structure()
        
    def _load_structure(self) -> Dict:
        """加载页面结构"""
        if not self.structure_path.exists():
            return {}
        with open(self.structure_path, 'r', encoding='utf-8') as f:
            return json.load(f)
    
    def generate(self, output_path: str, title: Optional[str] = None) -> str:
        """
        生成原型Demo HTML文件
        
        Args:
            output_path: 输出目录
            title: 页面标题
            
        Returns:
            生成的HTML文件路径
        """
        if not self.page_structure:
            print("[PrototypeGenerator] 没有页面结构数据")
            return ""
        
        page_title = title or self.page_structure.get('title', 'Prototype Demo')
        components = self.page_structure.get('components', [])
        layout_sections = self.page_structure.get('layout_sections', [])
        color_palette = self.page_structure.get('color_palette', [])
        typography = self.page_structure.get('typography', {})
        
        # 生成HTML
        html = self._generate_html(
            title=page_title,
            components=components,
            layout_sections=layout_sections,
            color_palette=color_palette,
            typography=typography
        )
        
        # 保存文件
        output_dir = Path(output_path)
        output_dir.mkdir(parents=True, exist_ok=True)
        
        timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
        output_file = output_dir / f"prototype_{timestamp}.html"
        
        with open(output_file, 'w', encoding='utf-8') as f:
            f.write(html)
        
        print(f"[PrototypeGenerator] 原型Demo已生成: {output_file}")
        return str(output_file)
    
